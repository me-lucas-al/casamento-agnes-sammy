import { describe, expect, it } from "vitest";
import { InvalidPublicIdError, PendingPhotoLimitError } from "@/modules/gallery/errors";
import { MAX_PENDING_PHOTOS_PER_GUEST } from "@/modules/gallery/lib/upload-rules";
import { isManagedPublicId } from "@/shared/lib/cloudinary/cloudinary-url";
import { FAKE_CLOUD_NAME } from "@/tests/helpers/fakes/fake-cloudinary";
import { asUser } from "@/tests/helpers/fakes/fake-session";
import { seedAdmin } from "@/tests/helpers/database/seeds/seed-user";
import { seedGuest } from "@/tests/helpers/database/seeds/seed-guest";
import { useTestDatabase } from "@/tests/helpers/database/use-test-database";
import { buildGalleryContext, uploadInput } from "./gallery-test-context";

describe("photo asset safety", () => {
  const testDatabase = useTestDatabase();
  const adminActor = async () => asUser("admin", { id: (await seedAdmin(testDatabase.db)).id });
  const candidate = { mimeType: "image/png", sizeBytes: 1024 };

  it("signs a server generated gallery public id with allowed formats", async () => {
    const { galleryModule } = buildGalleryContext(testDatabase.db);

    const first = await galleryModule.signUploadPhoto(asUser("guest"), candidate);
    const second = await galleryModule.signUploadPhoto(asUser("guest"), candidate);

    expect(isManagedPublicId("gallery", first.publicId)).toBe(true);
    expect(second.publicId).not.toBe(first.publicId);
    expect(first.allowedFormats).toBe("jpg,png,webp");
  });

  it.each([
    ["foreign host", (id: string) => `https://evil.com/${FAKE_CLOUD_NAME}/image/upload/v1/${id}.jpg`],
    ["other cloud", (id: string) => `https://res.cloudinary.com/other/image/upload/v1/${id}.jpg`],
    ["id only in the query", (id: string) => `https://res.cloudinary.com/x?${id}`],
  ])("rejects a url with %s", async (_label, buildUrl) => {
    const { galleryModule } = buildGalleryContext(testDatabase.db);
    const input = uploadInput();

    await expect(
      galleryModule.registerUploadedPhoto(await adminActor(), { ...input, url: buildUrl(input.cloudinaryPublicId) }),
    ).rejects.toBeInstanceOf(InvalidPublicIdError);
  });

  it("rejects public ids that were not generated by the server", async () => {
    const { galleryModule } = buildGalleryContext(testDatabase.db);
    const url = `https://res.cloudinary.com/${FAKE_CLOUD_NAME}/image/upload/v1/gallery/mine.jpg`;

    await expect(
      galleryModule.registerUploadedPhoto(await adminActor(), { cloudinaryPublicId: "gallery/mine", url }),
    ).rejects.toBeInstanceOf(InvalidPublicIdError);
  });

  it("rejects registering a public id already used by another photo", async () => {
    const { galleryModule } = buildGalleryContext(testDatabase.db);
    const input = uploadInput();
    await galleryModule.registerUploadedPhoto(await adminActor(), input);

    await expect(galleryModule.registerUploadedPhoto(await adminActor(), input)).rejects.toBeInstanceOf(
      InvalidPublicIdError,
    );
  });

  it("limits pending photos per guest", async () => {
    const { galleryModule } = buildGalleryContext(testDatabase.db);
    const guest = await seedGuest(testDatabase.db);
    const actor = asUser("guest", { guestId: guest.id });
    for (let index = 0; index < MAX_PENDING_PHOTOS_PER_GUEST; index += 1) {
      await galleryModule.registerUploadedPhoto(actor, uploadInput());
    }

    await expect(galleryModule.registerUploadedPhoto(actor, uploadInput())).rejects.toBeInstanceOf(
      PendingPhotoLimitError,
    );
    const otherGuest = await seedGuest(testDatabase.db);
    const other = asUser("guest", { guestId: otherGuest.id });
    await expect(galleryModule.registerUploadedPhoto(other, uploadInput())).resolves.toBeDefined();
  });

  it("does not limit couple uploads", async () => {
    const { galleryModule } = buildGalleryContext(testDatabase.db);
    for (let index = 0; index <= MAX_PENDING_PHOTOS_PER_GUEST; index += 1) {
      await galleryModule.registerUploadedPhoto(await adminActor(), uploadInput());
    }
  });
});

describe("photo asset cleanup", () => {
  const testDatabase = useTestDatabase();

  const adminActor = async () => asUser("admin", { id: (await seedAdmin(testDatabase.db)).id });

  async function registerApproved() {
    const context = buildGalleryContext(testDatabase.db);
    const { photo } = await context.galleryModule.registerUploadedPhoto(await adminActor(), uploadInput());
    return { ...context, photo };
  }

  it("deletes the row even when cloudinary destroy fails", async () => {
    const { galleryModule, cloudinaryClient, photo } = await registerApproved();
    cloudinaryClient.failOnDestroy = true;

    await expect(galleryModule.deletePhoto(await adminActor(), photo.id)).resolves.toBeDefined();

    expect(await galleryModule.photoRepository.findById(photo.id)).toBeNull();
  });

  it("rejects the photo even when cloudinary destroy fails", async () => {
    const { galleryModule, cloudinaryClient, photo } = await registerApproved();
    cloudinaryClient.failOnDestroy = true;

    await galleryModule.rejectPhoto(await adminActor(), photo.id);

    expect((await galleryModule.photoRepository.findById(photo.id))?.status).toBe("rejected");
  });
});
